import fs from 'fs';
import https from 'https';
import path from 'path';

// Change this to your GitHub username
const GITHUB_USERNAME = 'Dustu103';

// Optional: Provide a GitHub Personal Access Token to avoid rate limits
// You can pass it in the terminal like: GITHUB_TOKEN=your_token npm run update-projects
const GITHUB_TOKEN = process.env.GITHUB_TOKEN || '';

// Add the exact names of the repositories you want to showcase on your portfolio.
// If this array is empty [], it will automatically fetch your most recently updated public repos.
const REPOS_TO_SHOW = [];

const headers = { 'User-Agent': 'Node.js' };
let apiPath = `/users/${GITHUB_USERNAME}/repos?sort=updated&per_page=100`;

if (GITHUB_TOKEN) {
  headers['Authorization'] = `token ${GITHUB_TOKEN}`;
  apiPath = `/user/repos?sort=updated&per_page=100`;
}

const options = {
  hostname: 'api.github.com',
  path: apiPath,
  headers: headers
};

console.log(`Fetching latest projects from GitHub for user: ${GITHUB_USERNAME}...`);

https.get(options, (res) => {
  let data = '';
  res.on('data', (chunk) => {
    data += chunk;
  });

  res.on('end', () => {
    try {
      const repos = JSON.parse(data);
      if (!Array.isArray(repos)) {
        console.error('Error: Unexpected response from GitHub API', repos);
        return;
      }

      let filteredRepos = repos.filter(repo => !repo.fork);

      // If the user specified specific repos to show, filter by those exact names
      if (REPOS_TO_SHOW.length > 0) {
        filteredRepos = filteredRepos.filter(repo => REPOS_TO_SHOW.includes(repo.name));
        
        // Sort them in the exact order specified in the REPOS_TO_SHOW array
        filteredRepos.sort((a, b) => REPOS_TO_SHOW.indexOf(a.name) - REPOS_TO_SHOW.indexOf(b.name));
      } else {
        // Otherwise just take the top 6 most recent
        filteredRepos = filteredRepos.slice(0, 6);
      }

      const projects = filteredRepos.map(repo => ({
        id: repo.id,
        name: repo.name,
        description: repo.description || '',
        html_url: repo.html_url,
        language: repo.language || null,
        stargazers_count: repo.stargazers_count || 0,
        forks_count: repo.forks_count || 0,
      }));

      const fileContent = `import type { Project } from '@/types/portfolio';

// This file is auto-generated by running "npm run update-projects"
// Do not edit manually unless you know what you're doing.

export const projectsData: Project[] = ${JSON.stringify(projects, null, 2)};
`;

      const filePath = path.join(process.cwd(), 'utils', 'data', 'projects-data.ts');
      fs.writeFileSync(filePath, fileContent, 'utf-8');
      
      console.log('✅ Successfully updated utils/data/projects-data.ts with latest GitHub projects!');
    } catch (e) {
      console.error('Error parsing GitHub response:', e);
    }
  });
}).on('error', (e) => {
  console.error('Error fetching from GitHub:', e);
});
